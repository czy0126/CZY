"""Place the planned parts into the native EasyEDA project and wire their pads.

The placement plan carries pads already resolved to library pin numbers, so
this tool never has to guess which pad a golden pin means.  Placement and
wiring run in slices because the CLI caps one invocation at 60 s and a full
board is 83 parts and 280 wire stubs (five magnetics included).

Nothing here is trusted blindly either: after the last slice the caller is
expected to export the netlist and diff it against the golden one.  Placing
parts successfully proves only that the API answered.

The project must be opened by path in a fresh session:

    lceda-pro open --path "<...>.eprj2" --headless true
    python tools/lceda_place_main_board.py --emit           # write the slices
    python tools/lceda_place_main_board.py --all --session <id> --watch "<file>"
    python tools/lceda_place_main_board.py --netlist-ready --session <id>
    ... gen/export_netlist.js -> gen/netlist_export_raw.json

Calling ``dmt_Project.openProject(uuid)`` instead re-resolves the project (the
editor ends up pointing at its library/cloud copy) and every subsequent
``sch_Document.save()`` returns false while the file on disk stays untouched.
Measured: open by path + one text primitive -> save true, file grew 1572864 ->
1576960 bytes about 20 s later; the same edits after ``openProject(uuid)`` ->
save false, mtime unchanged.

Saving and exporting are mutually exclusive on a document that contains the
project-library magnetics.  A placed part with a non-empty
``otherProperty.Footprint`` cannot be serialised (save false, file untouched),
but while the magnetics have no footprint ``getNetlistFile()`` returns nothing.
So the file is written first and the footprint property is injected afterwards,
in memory only.  ``--netlist-ready`` is that second step; it must not be
followed by another save.

    python tools/lceda_place_main_board.py --slice 0        # run one slice
"""

from __future__ import annotations

import argparse
import json
import subprocess
import time
from pathlib import Path

import main_board_schematic as mbs

ROOT = Path(__file__).resolve().parent.parent
HW = ROOT / "hardware/dcx_main"
PLAN = HW / "placement_plan.json"
GEN = HW / "gen"
CLI = Path(r"D:\lceda-pro\lceda-pro.exe")
PROJECT = "14837d107b6a52feb21f43869dd7378616b33db49e6c75ae2ea6bc0a53989e46"

COLS = 6
DX, DY = 380, 300          # grid pitch: wide enough for a SON-10 plus its stubs
X0, Y0 = 220, 300
SECTION_GAP = 240          # vertical room for the next block's label
SLICE = 22                 # refs per invocation


def layout(plan: dict) -> tuple[dict[str, tuple[int, int]], list[tuple[str, int, int]]]:
    """Return ref positions and the section labels, in drawing order.

    Parts are laid out block by block rather than as one alphabetical grid, so
    the sheet reads as a signal chain.  A block whose parts are all unplaceable
    (the tank, today) gets no label -- an empty title over empty space would be
    worse than its absence, which the plan already records as a gap.
    """
    pos: dict[str, tuple[int, int]] = {}
    labels: list[tuple[str, int, int]] = []
    y = Y0
    for title, refs in mbs.SECTIONS:
        present = [r for r in refs if r in plan["refs"]]
        if not present:
            continue
        labels.append((title, X0, y - 130))
        for i, ref in enumerate(present):
            pos[ref] = (X0 + (i % COLS) * DX, y + (i // COLS) * DY)
        y += ((len(present) + COLS - 1) // COLS) * DY + SECTION_GAP
    return pos, labels


def emit(plan: dict, out: Path) -> list[Path]:
    """One JS file per slice: place the refs, then stub every pad to its net."""
    pos, labels = layout(plan)
    refs = [r for r in pos]           # layout order, i.e. section order
    files: list[Path] = []
    out.mkdir(parents=True, exist_ok=True)

    for start in range(0, len(refs), SLICE):
        chunk = refs[start:start + SLICE]
        payload = {
            "project": PROJECT,
            "clear": start == 0,
            # labels belong with the clear, so a re-run never stacks duplicates
            "labels": [{"text": t, "x": x, "y": y} for t, x, y in labels] if start == 0 else [],
            "parts": [
                {"ref": r, "uuid": plan["refs"][r]["uuid"],
                 "x": pos[r][0], "y": pos[r][1],
                 "library": plan["refs"][r].get("library", "system"),
                 "footprint_name": (plan["refs"][r].get("footprint") or {}).get("name", ""),
                 "pads": plan["refs"][r]["pads"]}
                for r in chunk
            ],
        }
        js = TEMPLATE.replace("__DATA__", json.dumps(payload, ensure_ascii=False))
        path = out / f"slice_{start // SLICE:02d}.js"
        path.write_text(js, encoding="utf-8")
        files.append(path)
    return files


TEMPLATE = r"""// generated by tools/lceda_place_main_board.py -- do not edit
const D = __DATA__;
const LIB = '0819f05c4eef4c71ace90d822a990e87';

// Never openProject() here: it re-resolves the project and save() then lies.
// The session must already be on this project, opened by path.
// The project uuid is on the envelope; data[] holds the boards, and data[0]
// is "Board1", not the project.  Opening by path is asynchronous: right after
// `lceda-pro open` the project info can still be empty, so wait for a board
// with a schematic page instead of reading data[0] once.
let info = null;
let board = null;
for (let i = 0; i < 20 && !board; i++) {
  info = await eda.dmt_Project.getCurrentProjectInfo();
  board = info && info.data ? info.data.find((b) => b && b.schematic && b.schematic.page && b.schematic.page.length) : null;
  if (!board) await new Promise((r) => setTimeout(r, 1000));
}
if (!board) return { error: 'project not loaded' };
const PROJ = info.uuid;
if (D.project && PROJ !== D.project) {
  return { error: 'wrong project open', want: D.project, got: PROJ };
}
const sch = board.schematic;
await eda.dmt_EditorControl.openDocument(sch.page[0].uuid);
await new Promise((r) => setTimeout(r, 1500));

const report = { placed: [], unwired: [], failed: [], labels: 0, saved: false };

if (D.clear) {
  const stale = (await eda.sch_PrimitiveComponent.getAll())
    .filter((c) => c.getState_Designator() || c.getState_ComponentType())
    .map((c) => c.getState_PrimitiveId());
  const wires = (await eda.sch_PrimitiveWire.getAll()).map((w) => w.getState_PrimitiveId());
  if (wires.length) await eda.sch_PrimitiveWire.delete(wires);
  if (stale.length) await eda.sch_PrimitiveComponent.delete(stale);
  // section labels are primitives too; without this a re-run stacks copies
  const texts = (await eda.sch_PrimitiveText.getAll()).map((t) => t.getState_PrimitiveId());
  if (texts.length) await eda.sch_PrimitiveText.delete(texts);
  for (const l of D.labels) {
    if (await eda.sch_PrimitiveText.create(l.x, l.y, l.text, 0)) report.labels++;
  }
}

for (const p of D.parts) {
  // A project-library device is keyed by the project uuid; a system device by
  // the library hash.  Using the wrong one makes create() hang until timeout.
  const lib = p.library === 'project' ? PROJ : LIB;
  const c = await eda.sch_PrimitiveComponent.create(
    { libraryType: '3', libraryUuid: lib, uuid: p.uuid }, p.x, p.y,
    undefined, 0, false, true, true);
  if (!c) { report.failed.push({ ref: p.ref, why: 'create returned null' }); continue; }
  const id = c.getState_PrimitiveId();
  const pre = (await eda.sch_PrimitiveComponent.get(id)).getState_OtherProperty();
  // Do NOT put p.footprint_name into pre.Footprint.  modify() moves that key
  // into the instance's footprint field as a *uuid*, so a footprint name lands
  // where a uuid belongs; the document then refuses to serialise and every
  // later save() returns false.  Measured: with the property -> save false,
  // file untouched; without it -> save true, file grew.  A project device
  // therefore stays unassociated until the association can be made at device
  // level, which lib_Device.modify() rejects in this build (see README).
  await eda.sch_PrimitiveComponent.modify(id, { designator: p.ref, otherProperty: pre });

  const cx = p.x, cy = p.y;
  const pins = await eda.sch_PrimitiveComponent.getAllPinsByPrimitiveId(id);
  const seen = new Set();
  for (const pin of pins) {
    const num = pin.getState_PinNumber();
    const net = p.pads[num];
    if (net === undefined) continue;
    const key = pin.x + ',' + pin.y;
    if (seen.has(key)) continue;           // stacked pads share one stub
    seen.add(key);
    const dx = pin.x - cx, dy = pin.y - cy;
    const ex = Math.abs(dx) >= Math.abs(dy) ? pin.x + (dx < 0 ? -20 : 20) : pin.x;
    const ey = Math.abs(dx) >= Math.abs(dy) ? pin.y : pin.y + (dy < 0 ? -20 : 20);
    const w = await eda.sch_PrimitiveWire.create([pin.x, pin.y, ex, ey], net);
    if (!w) report.unwired.push({ ref: p.ref, pad: num, net });
  }
  report.placed.push({ ref: p.ref, id, pins: pins.length });
}
// The write is debounced: save() returns before the file changes on disk, so
// the caller has to wait for the mtime/size to move (see --watch).
report.saved = await eda.sch_Document.save();
return report;
"""

# Injected *after* the file has been written, never before: a placed part with
# a non-empty otherProperty.Footprint cannot be serialised, so the property and
# the save are mutually exclusive.  sch_ManufactureData.getNetlistFile() returns
# nothing while the magnetics carry no footprint, so the export runs on a
# document that has already been saved and is no longer written back.
NETLIST_READY = r"""// generated by tools/lceda_place_main_board.py -- do not edit
const D = __DATA__;
let info = null;
let board = null;
for (let i = 0; i < 20 && !board; i++) {
  info = await eda.dmt_Project.getCurrentProjectInfo();
  board = info && info.data ? info.data.find((b) => b && b.schematic && b.schematic.page && b.schematic.page.length) : null;
  if (!board) await new Promise((r) => setTimeout(r, 1000));
}
if (!board) return { error: 'project not loaded' };
await eda.dmt_EditorControl.openDocument(board.schematic.page[0].uuid);
await new Promise((r) => setTimeout(r, 1500));
const injected = [];
for (const c of await eda.sch_PrimitiveComponent.getAll()) {
  const ref = c.getState_Designator();
  const fp = D.footprints[ref];   // footprint uuid, see netlist_ready()
  if (!fp) continue;
  const id = c.getState_PrimitiveId();
  const pre = (await eda.sch_PrimitiveComponent.get(id)).getState_OtherProperty();
  if (pre.Footprint) continue;
  pre.Footprint = fp;
  await eda.sch_PrimitiveComponent.modify(id, { otherProperty: pre });
  injected.push(ref);
}
return { injected };
"""


def run_code(session: str, code: str) -> dict:
    proc = subprocess.run(
        [str(CLI), "invoke", "--session", session, "--ext-uuid", "eda",
         "--timeout", "60000", "--code", code],
        capture_output=True, text=True, encoding="utf-8", errors="replace")
    return json.loads(proc.stdout.strip().splitlines()[0])


def run(session: str, script: Path) -> dict:
    return run_code(session, script.read_text(encoding="utf-8"))


def netlist_ready(plan: dict) -> dict[str, str]:
    """ref -> footprint uuid, for the parts whose device carries no footprint.

    The uuid, not the name: modify() moves otherProperty.Footprint into the
    instance's ``footprint.uuid``, so a name would produce a reference that
    resolves to nothing.  System devices already carry a real association and
    are left alone.
    """
    return {ref: str((spec.get("footprint") or {}).get("uuid") or "")
            for ref, spec in plan["refs"].items() if spec.get("unverified")}


def fingerprint(path: Path) -> tuple[int, int]:
    st = path.stat()
    return st.st_size, st.st_mtime_ns


def wait_for_write(path: Path, before: tuple[int, int], seconds: float = 90) -> bool:
    """save() returns true before the debounced write lands.  The file moving
    is the only evidence that it ever did -- a true return alone is not."""
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if fingerprint(path) != before:
            return True
        time.sleep(2)
    return False


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--emit", action="store_true", help="write the slice scripts")
    ap.add_argument("--slice", type=int, help="run slice N against a live session")
    ap.add_argument("--session", help="EasyEDA CLI session id")
    ap.add_argument("--all", action="store_true", help="run every slice in order")
    ap.add_argument("--watch", type=Path,
                    help=".eprj2 whose size/mtime must change after the last slice")
    ap.add_argument("--netlist-ready", action="store_true",
                    help="after the file is written, make the open document exportable")
    args = ap.parse_args(argv)

    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    if args.emit:
        files = emit(plan, GEN)
        print(f"wrote {len(files)} slice scripts")
        return 0

    if args.netlist_ready:
        if not args.session:
            ap.error("--session is required for --netlist-ready")
        code = NETLIST_READY.replace(
            "__DATA__", json.dumps({"footprints": netlist_ready(plan)}, ensure_ascii=False))
        res = run_code(args.session, code)
        if not res.get("ok"):
            print(f"netlist-ready FAILED {json.dumps(res.get('error'))[:300]}")
            return 1
        print(f"footprint properties injected: {res['value']['injected']}")
        return 0

    if args.slice is None and not args.all:
        ap.error("pass --emit, --slice or --all")
    if not args.session:
        ap.error("--session is required to run slices")

    files = sorted(GEN.glob("slice_*.js"))
    todo = files if args.all else [GEN / f"slice_{args.slice:02d}.js"]
    before = fingerprint(args.watch) if args.watch else None
    rc = 0
    for path in todo:
        res = run(args.session, path)
        if not res.get("ok"):
            print(f"{path.name}: FAILED {json.dumps(res.get('error'))[:300]}")
            return 1
        value = res["value"]
        if "placed" not in value:
            print(f"{path.name}: REFUSED {json.dumps(value)[:300]}")
            return 1
        print(f"{path.name}: placed {len(value['placed'])}, "
              f"unwired {len(value['unwired'])}, failed {len(value['failed'])}, "
              f"labels {value.get('labels', 0)}, saved {value.get('saved')}")
        for bad in value["failed"] + value["unwired"]:
            print("   ", bad)
        if value.get("saved") is not True:
            # placement that only ever lived in memory is not a drawn schematic
            print(f"{path.name}: save() did not return true")
            rc = 1

    if args.watch and before is not None:
        if wait_for_write(args.watch, before):
            print(f"{args.watch.name}: written (size {before[0]} -> {args.watch.stat().st_size})")
        else:
            print(f"{args.watch.name}: unchanged after 90 s -- the save never reached disk")
            rc = 1
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
