"""Place the planned parts into the native EasyEDA project and wire their pads.

The placement plan carries pads already resolved to library pin numbers, so
this tool never has to guess which pad a golden pin means.  Placement and
wiring run in slices because the CLI caps one invocation at 60 s and a full
board is 61 parts and 227 wire stubs.

Nothing here is trusted blindly either: after the last slice the caller is
expected to export the netlist and diff it against the golden one.  Placing
parts successfully proves only that the API answered.

    python tools/lceda_place_main_board.py --emit           # write the slices
    python tools/lceda_place_main_board.py --slice 0        # run one slice
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HW = ROOT / "hardware/dcx_main"
PLAN = HW / "placement_plan.json"
GEN = HW / "gen"
CLI = Path(r"D:\lceda-pro\lceda-pro.exe")
PROJECT = "14837d107b6a52feb21f43869dd7378616b33db49e6c75ae2ea6bc0a53989e46"

COLS = 6
DX, DY = 380, 300          # grid pitch: wide enough for a SON-10 plus its stubs
X0, Y0 = 220, 200
SLICE = 22                 # refs per invocation


def positions(refs: list[str]) -> dict[str, tuple[int, int]]:
    return {ref: (X0 + (i % COLS) * DX, Y0 + (i // COLS) * DY) for i, ref in enumerate(refs)}


def emit(plan: dict, out: Path) -> list[Path]:
    """One JS file per slice: place the refs, then stub every pad to its net."""
    refs = list(plan["refs"])
    pos = positions(refs)
    files: list[Path] = []
    out.mkdir(parents=True, exist_ok=True)

    for start in range(0, len(refs), SLICE):
        chunk = refs[start:start + SLICE]
        payload = {
            "project": PROJECT,
            "clear": start == 0,
            "parts": [
                {"ref": r, "uuid": plan["refs"][r]["uuid"],
                 "x": pos[r][0], "y": pos[r][1],
                 "pads": plan["refs"][r]["pads"]}
                for r in chunk
            ],
        }
        js = TEMPLATE.replace("__DATA__", json.dumps(payload, ensure_ascii=False))
        path = out / f"slice_{start // SLICE:02d}.js"
        path.write_text(js, encoding="utf-8")
        files.append(path)
    return files


TEMPLATE = r"""// generated by tools/lceda_place_main_board.py -- do not edit
const D = __DATA__;
const LIB = '0819f05c4eef4c71ace90d822a990e87';

await eda.dmt_Project.openProject(D.project);
await new Promise((r) => setTimeout(r, 1500));
const info = await eda.dmt_Project.getCurrentProjectInfo();
const sch = info.data[0].schematic;
await eda.dmt_EditorControl.openDocument(sch.page[0].uuid);
await new Promise((r) => setTimeout(r, 2000));

if (D.clear) {
  const stale = (await eda.sch_PrimitiveComponent.getAll())
    .filter((c) => c.getState_Designator() || c.getState_ComponentType())
    .map((c) => c.getState_PrimitiveId());
  const wires = (await eda.sch_PrimitiveWire.getAll()).map((w) => w.getState_PrimitiveId());
  if (wires.length) await eda.sch_PrimitiveWire.delete(wires);
  if (stale.length) await eda.sch_PrimitiveComponent.delete(stale);
}

const report = { placed: [], unwired: [], failed: [] };
for (const p of D.parts) {
  const c = await eda.sch_PrimitiveComponent.create(
    { libraryType: '3', libraryUuid: LIB, uuid: p.uuid }, p.x, p.y,
    undefined, 0, false, true, true);
  if (!c) { report.failed.push({ ref: p.ref, why: 'create returned null' }); continue; }
  const id = c.getState_PrimitiveId();
  const pre = (await eda.sch_PrimitiveComponent.get(id)).getState_OtherProperty();
  await eda.sch_PrimitiveComponent.modify(id, { designator: p.ref, otherProperty: pre });

  const cx = p.x, cy = p.y;
  const pins = await eda.sch_PrimitiveComponent.getAllPinsByPrimitiveId(id);
  const seen = new Set();
  for (const pin of pins) {
    const num = pin.getState_PinNumber();
    const net = p.pads[num];
    if (net === undefined) continue;
    const key = pin.x + ',' + pin.y;
    if (seen.has(key)) continue;           // stacked pads share one stub
    seen.add(key);
    const dx = pin.x - cx, dy = pin.y - cy;
    const ex = Math.abs(dx) >= Math.abs(dy) ? pin.x + (dx < 0 ? -20 : 20) : pin.x;
    const ey = Math.abs(dx) >= Math.abs(dy) ? pin.y : pin.y + (dy < 0 ? -20 : 20);
    const w = await eda.sch_PrimitiveWire.create([pin.x, pin.y, ex, ey], net);
    if (!w) report.unwired.push({ ref: p.ref, pad: num, net });
  }
  report.placed.push({ ref: p.ref, id, pins: pins.length });
}
return report;
"""


def run(session: str, script: Path) -> dict:
    proc = subprocess.run(
        [str(CLI), "invoke", "--session", session, "--ext-uuid", "eda",
         "--timeout", "60000", "--code", script.read_text(encoding="utf-8")],
        capture_output=True, text=True, encoding="utf-8", errors="replace")
    return json.loads(proc.stdout.strip().splitlines()[0])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--emit", action="store_true", help="write the slice scripts")
    ap.add_argument("--slice", type=int, help="run slice N against a live session")
    ap.add_argument("--session", help="EasyEDA CLI session id")
    ap.add_argument("--all", action="store_true", help="run every slice in order")
    args = ap.parse_args(argv)

    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    if args.emit:
        files = emit(plan, GEN)
        print(f"wrote {len(files)} slice scripts")
        return 0

    if args.slice is None and not args.all:
        ap.error("pass --emit, --slice or --all")
    if not args.session:
        ap.error("--session is required to run slices")

    files = sorted(GEN.glob("slice_*.js"))
    todo = files if args.all else [GEN / f"slice_{args.slice:02d}.js"]
    for path in todo:
        res = run(args.session, path)
        if not res.get("ok"):
            print(f"{path.name}: FAILED {json.dumps(res.get('error'))[:300]}")
            return 1
        value = res["value"]
        print(f"{path.name}: placed {len(value['placed'])}, "
              f"unwired {len(value['unwired'])}, failed {len(value['failed'])}")
        for bad in value["failed"] + value["unwired"]:
            print("   ", bad)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
