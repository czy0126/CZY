"""Fail-closed evidence review for independent, settled 48/50V 120A hot faults.

A 3.982V SS threshold only establishes the RT-only frequency regime.
It cannot establish settled Vout, correct fault injection, turn-off
or post-fault recovery. A saved .validation.json is only a LOG precheck.

This helper accepts a candidate *only* when an evidence report and separate
waveform engineering review are both explicitly attached and digest-matched.
It does not run LTspice or claim hardware protection/thermal SOA.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PP = ROOT / "design/v3/power_priority"
CASES = ("48v_120a", "50v_120a")


def _valid_repo_file(name: object, digest: object) -> Path | None:
    if not isinstance(name, str) or not name or not isinstance(digest, str):
        return None
    if len(digest) != 64:
        return None
    rel = Path(name)
    if rel.is_absolute() or ".." in rel.parts or ":" in name or name.startswith("\\\\"):
        return None
    full = (ROOT / rel).resolve()
    if not full.is_relative_to(ROOT.resolve()) or not full.is_file():
        return None
    if hashlib.sha256(full.read_bytes()).hexdigest() != digest.lower():
        return None
    return full


def inspect(case: str) -> dict:
    if case not in CASES:
        raise ValueError(f"unsupported hot fault case: {case}")
    # Recorded RAW analysis is a hard lower-level prerequisite. A human
    # approval JSON must never overrule a solver prefix or a still-high SR gate.
    # The 48V deck reaches Tstop but one SR gate is high at the end; the 50V
    # deck has BOTH a partial solve and a high SR gate. Neither is a safe
    # full-duration protection certification without a corrected run.
    measured = PP / f"hotfault_{case}.json"
    if not measured.is_file():
        return {"case": case, "accepted": False,
                "reason": "independent original RAW analysis absent"}
    try:
        actual = json.loads(measured.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"case": case, "accepted": False,
                "reason": "invalid original RAW analysis"}
    if (actual.get("reached_tstop") is not True or
        actual.get("solver_prefix_only") is not False):
        return {"case": case, "accepted": False,
                "reason": "RAW analysis ended before requested Tstop; solver prefix is not full fault evidence"}
    if actual.get("fault", {}).get("sr_gate_latched_at_end") is not False:
        return {"case": case, "accepted": False,
                "reason": "SR gate still high at end of fault trace; shutdown not demonstrated"}
    approval = PP / f"hotfault_{case}_engineering_review.json"
    if not approval.is_file():
        return {"case": case, "accepted": False,
                "reason": "independent engineering waveform review absent"}
    try:
        j = json.loads(approval.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"case": case, "accepted": False, "reason": "invalid engineering review"}
    if (j.get("approved") is not True or
        not isinstance(j.get("reviewer"), str) or not j["reviewer"].strip() or
        not isinstance(j.get("revision"), str) or not j["revision"].strip()):
        return {"case": case, "accepted": False, "reason": "approval/reviewer/revision missing"}
    report = _valid_repo_file(j.get("validation_path"), j.get("validation_sha256"))
    waveform = _valid_repo_file(j.get("waveform_review_path"),
                                j.get("waveform_review_sha256"))
    if report is None or waveform is None or report == waveform:
        return {"case": case, "accepted": False,
                "reason": "original LOG precheck and separate waveform review missing or mismatched"}
    try:
        v = json.loads(report.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"case": case, "accepted": False, "reason": "invalid LOG precheck"}
    from validate_hotfault_log import CASES as CONFIG, sha
    if not (v.get("case") == case and
            v.get("status") == "LOG_PRECHECK_PASS_REQUIRES_WAVEFORM_AND_DEVICE_REVIEW" and
            v.get("blockers") == [] and v.get("not_rated") is True and
            v.get("raw_bytes", 0) > 0 and
            v.get("deck_sha256") == sha(CONFIG[case]["deck"]) and
            v.get("raw_bytes") == actual.get("raw_bytes")):
        return {"case": case, "accepted": False,
                "reason": "simulation precheck mismatches current deck or was not valid"}
    # No autogenerated certificate can replace human engineering judgement.
    required = ("pre_fault_settled", "switch_and_oc_verified",
                "gate_shutdown_verified", "peak_stress_reviewed",
                "waveform_full_duration_verified")
    if not all(j.get(k) is True for k in required):
        return {"case": case, "accepted": False,
                "reason": "waveform/shutdown/peak-stress/full-duration signoffs incomplete"}
    return {"case": case, "accepted": True,
            "reason": "simulation engineering review documented; NOT hardware rated"}


def build() -> dict:
    items = [inspect(case) for case in CASES]
    return {"status": "ENGINEERING_SIMULATION_ACCEPTED" if all(
        item["accepted"] for item in items) else "HOT_FAULT_SIMULATION_NOT_VERIFIED",
        "cases": items,
        "all_independent_hotfault_cases_accepted": all(
            item["accepted"] for item in items),
        "hardware_continuous_rating_approved": False}
