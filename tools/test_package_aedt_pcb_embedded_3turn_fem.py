"""Verify actual saved AEDT 3turn 1A FEM, solver/mesh archives and non-fab gates."""
from __future__ import annotations
import hashlib
import json
import sys
from pathlib import Path

import pytest

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/"tools"))
import package_aedt_pcb_embedded_3turn_fem as S

def read():
    return json.loads(S.EVID.read_text(encoding="utf-8"))

def test_real_native_fem_artifacts_digest_and_29_field_records():
    e=read()
    assert e["status"]=="NATIVE_REAL_6LAYER_3TURN_PCB_1A_FEM_CONVERGED_GENERIC_FERRITE_ONLY_NOT_FOR_FAB"
    assert e["origin"]=="Ansys Electronics Desktop 2025R2 local actual Maxwell3D Solve"
    assert e["native_3turn_CAD_model_sha256"]==S.digest(S.GEOM)
    assert e["results_archive_sha256"]==S.digest(S.ZIP)
    assert e["results_archive"]["count"]==29
    assert e["results_archive"]["total_uncompressed_bytes"]>20_000_000
    assert S.ZIP.stat().st_size>5_000_000
    assert e["retained_files_sha256"]=={
        k:S.hash_retained(k,dst) for k,(_,dst) in S.MAP.items()}
    assert S.extract(S.ZIP)==e["results_archive"]

def test_real_convergence_and_true_ANSYS_energy_reporter_crosscheck():
    e=read()
    assert e["actual_native_solver_mesh_passes"]==2
    assert e["actual_mesh_tetrahedra_last"]==58_262
    assert e["actual_last_mesh_energy_error_pct"]==pytest.approx(5.7135)
    assert e["actual_last_mesh_delta_energy_pct"]==pytest.approx(5.3555)
    assert e["Ansys_field_reporter_energy_j"]==pytest.approx(8.92655401743118e-7)
    assert e["Ansys_field_reporter_energy_equivalent_1A_uH"]==pytest.approx(1.7853108034862362)
    conv=S.MAP["convergence"][1].read_text(encoding="utf-8")
    rows=S.parse_conv(conv)
    assert rows==e["actual_native_solver_energy_rows"]
    assert rows[0]["tetrahedra"]==48577
    assert rows[-1]["error_pct"]<7

def test_actual_solver_success_does_not_fake_N97_or_fabrication():
    e=read()
    assert e["bias_1A_DC"] is True
    assert e["model_contains_external_artificial_leads"] is True
    assert e["generic_stock_ferrite_not_OEM_N97"] is True
    for key in ("N97_100C_appropriate_BH_verified",
                "full_range_L_I_and_0p92uH_nominal_inductance_verified",
                "200kHz_AC_and_100C_core_copper_loss_verified",
                "manufacturer_core_machining_and_6layer_barrel_qualified",
                "16mm_total_assembly_and_safety_qualified",
                "OEM_real_transformer_T1_T4_CT_validated",
                "hardware_or_100A_delivery_approved",
                "fabrication_approved"):
        assert e[key] is False

def test_solved_source_is_true_saved_reopened_native_PCB_coil():
    native_receipt=json.loads(S.MAP["native_receipt"][1].read_text(encoding="utf-8"))
    energy=json.loads(S.MAP["field_energy"][1].read_text(encoding="utf-8"))
    assert native_receipt["source_sha256"]==S.digest(S.GEOM)
    assert native_receipt["native_validate_design_passed"]
    assert native_receipt["solver_normal_completion"]
    assert native_receipt["native_mesh_converged"]
    assert native_receipt["excitation_a"]==1
    assert native_receipt["maximum_mesh_passes"]==3
    assert all(n in native_receipt["actual_end_terminal_faces"] for n in ("IN","OUT"))
    assert energy["source_project_unchanged"]
    assert energy["energy_equivalent_uH"]>1.0

def test_native_package_generator_check_no_solver_license_needed():
    solved=json.loads(S.MAP["native_receipt"][1].read_text(encoding="utf-8"))
    energy=json.loads(S.MAP["field_energy"][1].read_text(encoding="utf-8"))
    conv=S.MAP["convergence"][1].read_text(encoding="utf-8")
    files={k:S.hash_retained(k,dst) for k,(src,dst) in S.MAP.items()}
    assert S.summarize(solved,energy,conv,files,S.ZIP)==read()

def test_malformed_fake_native_convergence_is_rejected():
    with pytest.raises(ValueError,match="native|sequential|No true"):
        S.parse_conv("NOT ANSYS ENERGY GENERATED BY AUTHOR")
    actual=S.MAP["convergence"][1].read_text(encoding="utf-8")
    with pytest.raises(ValueError,match="implausible|Implausible"):
        S.parse_conv(actual.replace("58262","2"))
    with pytest.raises(ValueError,match="real|sequential|No true"):
        S.parse_conv(actual.replace("   2|","   4|"))

def test_fake_manufacturer_approval_and_unqualified_solver_prohibited():
    solved=json.loads(S.MAP["native_receipt"][1].read_text(encoding="utf-8"))
    energy=json.loads(S.MAP["field_energy"][1].read_text(encoding="utf-8"))
    conv=S.MAP["convergence"][1].read_text(encoding="utf-8")
    solved["N97_100C_BH_verified"]=True
    with pytest.raises(ValueError,match="falsely approved"):
        S.checked_inputs(solved,energy,conv)
